import type { ReviewDoc } from '@wwi/scenario';

/** Written near the top of every generated review, so `sim review` never reads one back as a research note. */
export const REVIEW_MARKER = 'Generated by `sim review`; do not edit by hand.';

const cell = (s: string | undefined): string => (s ?? '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

/** The questions under "## Open questions for the historian" in a research note, each labelled with its file. */
export function extractOpenQuestions(markdown: string, file: string): string[] {
  const lines = markdown.split('\n');
  const start = lines.findIndex((l) => l.trim() === '## Open questions for the historian');
  if (start < 0) return [];
  const items: string[] = [];
  for (const line of lines.slice(start + 1)) {
    if (/^#{1,2} /.test(line)) break;
    const top = /^(?:[-*]|\d+\.) (.*)$/.exec(line);
    if (top) items.push(top[1]!);
    else if (items.length && line.trim()) items[items.length - 1] += ` ${line.trim().replace(/^[-*] /, '')}`;
  }
  return items.map((t) => `[${file}] ${t.replace(/\*\*/g, '')}`);
}

export function reviewToMarkdown(doc: ReviewDoc, openQuestions: string[] = doc.openQuestions): string {
  const c = doc.counts;
  const out: string[] = [
    `# Review: ${doc.scenarioTitle}`,
    '',
    `Status: \`${doc.status}\`. ${REVIEW_MARKER}`,
    '',
    '## Summary',
    '',
    `- Values: ${c.values}`,
    `- Sourced: ${c.sourced}`,
    `- Estimates: ${c.estimates}`,
    `- Disputed: ${c.disputed}`,
    `- By source tier (sourced values; a disputed value counts under its best source): ` +
      Object.entries(c.byTier).map(([t, n]) => `${t} ${n}`).join(', '),
    '',
    'Estimates are listed first in each section. Leader ratings are the builder\'s drafts and are yours to change. ' +
      'Doctrine and model-table rows give each parameter\'s meaning after its value; "calibrated (Plan 4)" marks a model ' +
      'coefficient that is fitted, not looked up.',
    '',
  ];
  if (doc.defaults?.length) {
    out.push('## Engine defaults', '', 'The engine fills these in because the scenario leaves them out; each run lists them in its defaultsUsed.', '');
    for (const d of doc.defaults) out.push(`- ${d}`);
    out.push('');
  }
  for (const s of doc.sections) {
    out.push(`## ${s.title}`, '');
    if (!s.rows.length) {
      out.push('No values.', '');
      continue;
    }
    out.push('| Value | How it is known | Source | Note |', '| --- | --- | --- | --- |');
    for (const r of s.rows) {
      const what = r.description ? `${cell(r.value)} — ${cell(r.description)}` : cell(r.value);
      out.push(`| **${cell(r.label)}**: ${what} | ${r.kind} | ${cell(r.cite)} | ${cell(r.note)} |`);
    }
    out.push('');
  }
  out.push('## Open questions for the historian', '');
  if (!openQuestions.length) out.push('None recorded.');
  openQuestions.forEach((q, i) => out.push(`${i + 1}. ${q.replace(/\s*\n\s*/g, ' ')}`));
  out.push(
    '',
    '## Checklist',
    '',
    '- [ ] Every estimate confirmed or corrected.',
    '- [ ] Every leader rating confirmed or changed.',
    '- [ ] Every disputed value settled or its range accepted.',
    '- [ ] Open questions answered or accepted.',
    '',
    'When every row is confirmed or corrected, change `status: draft` to `status: reviewed` in scenario.yaml.',
    '',
  );
  return out.join('\n');
}
